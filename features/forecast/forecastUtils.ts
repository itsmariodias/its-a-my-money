type TxLike = Pick<Transaction, 'account_id' | 'type' | 'amount' | 'date' | 'recurring_transaction_id'>;
type TransferLike = Pick<Transfer, 'from_account_id' | 'to_account_id' | 'amount' | 'to_amount' | 'date'>;

/** Fewer days of history than this and the spending average is noise, so it is left out. */
export const MIN_TREND_DAYS = 14;

/**
 * How one recurring occurrence moves the combined balance of `accountIds`.
 * A transfer between two accounts in scope moves nothing.
 */
export function scopeDelta(
  occurrence: Pick<RecurringOccurrence, 'amount' | 'kind' | 'type' | 'account_id' | 'to_account_id'>,
  accountIds: ReadonlySet<number>,
): number {
  const fromIn = accountIds.has(occurrence.account_id);
  if (occurrence.kind === 'transfer') {
    const toIn = occurrence.to_account_id !== null && accountIds.has(occurrence.to_account_id);
    if (fromIn === toIn) return 0;
    return fromIn ? -occurrence.amount : occurrence.amount;
  }
  if (!fromIn) return 0;
  return occurrence.type === 'income' ? occurrence.amount : -occurrence.amount;
}

/**
 * Average daily net (income − expense) of the hand-entered transactions on `accountIds` over the
 * last `lookbackDays` up to today. Rows generated by a recurring item are skipped — the forecast
 * adds those from the schedule. Null when there is under MIN_TREND_DAYS of history.
 */
export function dailyTrend(
  transactions: readonly TxLike[],
  accountIds: ReadonlySet<number>,
  today: string,
  lookbackDays = 90,
): number | null {
  const windowStart = addDays(today, -lookbackDays + 1);
  let earliest: string | null = null;
  let net = 0;
  for (const t of transactions) {
    if (!accountIds.has(t.account_id) || t.date > today) continue;
    if (earliest === null || t.date < earliest) earliest = t.date;
    if (t.date < windowStart || t.recurring_transaction_id !== null) continue;
    net += t.type === 'income' ? t.amount : -t.amount;
  }
  if (earliest === null) return null;
  const days = Math.min(lookbackDays, daysBetween(earliest, today) + 1);
  if (days < MIN_TREND_DAYS) return null;
  return net / days;
}

/** [step, 2·step, …, total] — always ends exactly on `total`. */
function stepOffsets(total: number, step: number): number[] {
  const out: number[] = [];
  for (let n = step; n < total; n += step) out.push(n);
  out.push(total);
  return out;
}

export interface ForecastPoint {
  date: string;
  value: number;
  projected: boolean;
}

export interface BalanceForecast {
  points: ForecastPoint[];
  endValue: number;
  trendPerDay: number | null;
}

/**
 * Combined balance of `accounts` for the last `pastDays`, then projected `futureDays` ahead.
 * A future point is the balance with every row dated up to it (future-dated entries included),
 * plus the recurring items due by then, plus the daily trend times the days elapsed.
 */
export function balanceForecast({
  accounts,
  transactions,
  transfers,
  recurring,
  today,
  pastDays = 90,
  futureDays = 90,
  stepDays = 7,
}: {
  accounts: readonly Account[];
  transactions: readonly TxLike[];
  transfers: readonly TransferLike[];
  recurring: readonly RecurringTemplate[];
  today: string;
  pastDays?: number;
  futureDays?: number;
  stepDays?: number;
}): BalanceForecast {
  const accountIds = new Set(accounts.map((a) => a.id));
  const flowAt = (date: string) =>
    accounts.reduce((sum, acc) => sum + accountFlowAsOf(acc, transactions, transfers, { endInclusive: date }), 0);

  const trendPerDay = dailyTrend(transactions, accountIds, today);
  const occurrences = expandOccurrences(recurring, addDays(today, 1), addDays(today, futureDays))
    .map((o) => ({ date: o.date, delta: scopeDelta(o, accountIds) }));

  const points: ForecastPoint[] = [
    ...stepOffsets(pastDays, stepDays).reverse().map((n) => {
      const date = addDays(today, -n);
      return { date, value: flowAt(date), projected: false };
    }),
    { date: today, value: flowAt(today), projected: false },
    ...stepOffsets(futureDays, stepDays).map((n) => {
      const date = addDays(today, n);
      const scheduled = occurrences.reduce((sum, o) => (o.date <= date ? sum + o.delta : sum), 0);
      return { date, value: flowAt(date) + scheduled + (trendPerDay ?? 0) * n, projected: true };
    }),
  ];

  return { points, endValue: points[points.length - 1].value, trendPerDay };
}

export interface MonthlyCashflow {
  month: string; // YYYY-MM
  income: number;
  expense: number;
  transferIn: number;
  transferOut: number;
}

/**
 * Income and expense per month for the `months` months ending at `endMonth`, oldest first.
 * With `transferView`, also the transfers into and out of that one account. Across several
 * accounts transfers stay at zero: between accounts in view they are the same money twice.
 */
export function monthlyCashflow(
  transactions: readonly Pick<Transaction, 'account_id' | 'type' | 'amount' | 'date'>[],
  accountIds: ReadonlySet<number>,
  endMonth: string,
  months: number,
  transferView?: { transfers: readonly TransferWithDetails[]; accountId: number },
): MonthlyCashflow[] {
  const rows: MonthlyCashflow[] = [];
  const byMonth: Record<string, MonthlyCashflow> = {};
  for (let i = months - 1; i >= 0; i--) {
    const row = { month: shiftMonth(endMonth, -i), income: 0, expense: 0, transferIn: 0, transferOut: 0 };
    rows.push(row);
    byMonth[row.month] = row;
  }
  for (const t of transactions) {
    if (!accountIds.has(t.account_id)) continue;
    const row = byMonth[monthKeyOf(t.date)];
    if (!row) continue;
    if (t.type === 'income') row.income += t.amount;
    else row.expense += t.amount;
  }
  if (transferView) {
    const { transfers, accountId } = transferView;
    for (const t of transfers) {
      if (t.from_account_id !== accountId && t.to_account_id !== accountId) continue;
      const row = byMonth[monthKeyOf(t.date)];
      if (!row) continue;
      const side = getTransferSide(t, accountId, '');
      if (side.isOutgoing) row.transferOut += side.amount;
      else row.transferIn += side.amount;
    }
  }
  return rows;
}

/**
 * Average monthly net and savings rate over the rows that can have data: from the first month
 * with any activity up to `currentMonth`. Empty leading months (before the user started) and
 * future months would only drag the average toward zero. Null when no month qualifies.
 * Transfers count as activity — an account fed only by transfers still has a chart — but not
 * toward the net or the rate: moving money is not earning or spending it.
 */
export function cashflowSummary(
  rows: readonly MonthlyCashflow[],
  currentMonth: string,
): { avgNet: number; savingsRate: number | null } | null {
  const firstActive = rows.findIndex((r) => r.income !== 0 || r.expense !== 0 || r.transferIn !== 0 || r.transferOut !== 0);
  if (firstActive === -1) return null;
  const counted = rows.slice(firstActive).filter((r) => r.month <= currentMonth);
  if (counted.length === 0) return null;
  const income = counted.reduce((s, r) => s + r.income, 0);
  const expense = counted.reduce((s, r) => s + r.expense, 0);
  return {
    avgNet: (income - expense) / counted.length,
    savingsRate: income > 0 ? ((income - expense) / income) * 100 : null,
  };
}

export interface ChartAxis {
  min: number;
  max: number;
  step: number;
  sections: number;
}

/**
 * Round axis bounds that cover `min..max` in about `targetSections` steps of 1, 2, 2.5 or 5 × 10ⁿ.
 * The bounds are multiples of the step, so an axis crossing zero has a 0 line.
 */
export function niceAxis(min: number, max: number, targetSections = 4): ChartAxis {
  const span = max - min;
  const raw = span > 0 ? span / targetSections : Math.abs(max) * 0.1 || 1;
  const magnitude = 10 ** Math.floor(Math.log10(raw));
  const norm = raw / magnitude;
  const nice = norm <= 1 ? 1 : norm <= 2 ? 2 : norm <= 2.5 ? 2.5 : norm <= 5 ? 5 : 10;
  const step = nice * magnitude;
  const axisMin = Math.floor(min / step) * step;
  let axisMax = Math.ceil(max / step) * step;
  if (axisMax === axisMin) axisMax += step;
  return { min: axisMin, max: axisMax, step, sections: Math.round((axisMax - axisMin) / step) };
}

/** "Oct 31" — the forecast chart's axis label for a YYYY-MM-DD day. */
export function shortDayLabel(day: string): string {
  return format(parseDay(day), 'MMM d');
}

/** "Oct" for a trend bar, "October 2026" for the detail line and screen readers. */
export function monthLabel(month: string, style: 'short' | 'long'): string {
  return format(parseMonth(month), style === 'short' ? 'MMM' : 'MMMM yyyy');
}

/** The last month the trend chart shows: December of the year in year mode, else the selected month. */
export function trendEndMonth(periodMode: PeriodMode, periodDate: Date): string {
  return toMonth(periodMode === 'year' ? endOfYear(periodDate) : periodDate);
}
