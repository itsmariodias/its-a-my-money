const account = (id: number, initial_balance = 0): Account => ({
  id,
  name: `Account ${id}`,
  initial_balance,
  icon: 'wallet',
  color: '#000',
  account_type: 'cash',
  current_value: null,
  currency: 'EUR',
  created_at: '2026-01-01',
});

const tx = (
  date: string,
  amount: number,
  type: 'income' | 'expense' = 'expense',
  account_id = 1,
  recurring_transaction_id: number | null = null,
): Pick<Transaction, 'account_id' | 'type' | 'amount' | 'date' | 'recurring_transaction_id'> => ({
  date, amount, type, account_id, recurring_transaction_id,
});

const recurring = (overrides: Partial<RecurringTemplate>): RecurringTemplate => ({
  amount: 100,
  kind: 'transaction',
  type: 'expense',
  category_id: 1,
  account_id: 1,
  to_account_id: null,
  frequency: 'monthly',
  end_date: null,
  next_due_date: '2026-11-01',
  is_active: 1,
  ...overrides,
  start_date: overrides.start_date ?? overrides.next_due_date ?? '2026-11-01',
});

const noTransfers: Pick<Transfer, 'from_account_id' | 'to_account_id' | 'amount' | 'to_amount' | 'date'>[] = [];

describe('scopeDelta', () => {
  const scope = new Set([1, 2]);

  it('adds income and subtracts expenses on an account in scope', () => {
    // Given a recurring income and expense on account 1
    // Then income raises and expense lowers the scoped balance
    expect(scopeDelta(recurring({ type: 'income', amount: 50 }), scope)).toBe(50);
    expect(scopeDelta(recurring({ type: 'expense', amount: 50 }), scope)).toBe(-50);
  });

  it('ignores transactions on accounts outside the scope', () => {
    // Given a recurring expense on account 9, which is not in scope
    expect(scopeDelta(recurring({ account_id: 9 }), scope)).toBe(0);
  });

  it('counts a transfer by which side is in scope', () => {
    // Given recurring transfers out of, into, and within the scope
    const out = recurring({ kind: 'transfer', type: null, account_id: 1, to_account_id: 9, amount: 30 });
    const into = recurring({ kind: 'transfer', type: null, account_id: 9, to_account_id: 2, amount: 30 });
    const internal = recurring({ kind: 'transfer', type: null, account_id: 1, to_account_id: 2, amount: 30 });
    // Then out subtracts, in adds, and internal moves nothing
    expect(scopeDelta(out, scope)).toBe(-30);
    expect(scopeDelta(into, scope)).toBe(30);
    expect(scopeDelta(internal, scope)).toBe(0);
  });
});

describe('dailyTrend', () => {
  const scope = new Set([1]);

  it('averages hand-entered net flow over the lookback window', () => {
    // Given 90 days of history: €900 of expenses and €1800 of income inside the window
    const rows = [
      tx('2026-07-01', 5),             // earliest row, outside the window — sets history length only
      tx('2026-08-10', 900),
      tx('2026-09-01', 1800, 'income'),
    ];
    // When averaging over 90 days to 2026-10-31
    const trend = dailyTrend(rows, scope, '2026-10-31');
    // Then the trend is +€900 / 90 days
    expect(trend).toBeCloseTo(10);
  });

  it('skips rows generated by a recurring item so they are not counted twice', () => {
    // Given a recurring-generated salary and a hand-entered expense
    const rows = [
      tx('2026-07-01', 0),
      tx('2026-10-01', 3000, 'income', 1, 7),
      tx('2026-10-02', 90),
    ];
    // Then only the hand-entered expense contributes
    expect(dailyTrend(rows, scope, '2026-10-31')).toBeCloseTo(-1);
  });

  it('divides by the days of history when shorter than the lookback', () => {
    // Given a user who started 30 days ago
    const rows = [tx('2026-10-02', 300)];
    // Then the average spreads over those 30 days, not 90
    expect(dailyTrend(rows, scope, '2026-10-31')).toBeCloseTo(-10);
  });

  it('returns null with under two weeks of history', () => {
    // Given 10 days of history
    expect(dailyTrend([tx('2026-10-22', 100)], scope, '2026-10-31')).toBeNull();
  });

  it('ignores future-dated rows and other accounts', () => {
    // Given only a future-dated row in scope and an old row elsewhere
    const rows = [tx('2026-12-01', 100), tx('2026-01-01', 100, 'expense', 2)];
    expect(dailyTrend(rows, scope, '2026-10-31')).toBeNull();
  });
});

describe('balanceForecast', () => {
  it('ends the history exactly on today and the projection exactly at futureDays', () => {
    // Given one account with no activity
    const { points } = balanceForecast({
      accounts: [account(1, 100)],
      transactions: [],
      transfers: noTransfers,
      recurring: [],
      today: '2026-10-31',
    });
    // Then today is the last unprojected point and the last point is 90 days out
    const lastPast = points.filter((p) => !p.projected).pop();
    expect(lastPast?.date).toBe('2026-10-31');
    expect(points[0].date).toBe('2026-08-02');
    expect(points[points.length - 1].date).toBe('2027-01-29');
    expect(points.every((p) => p.value === 100)).toBe(true);
  });

  it('projects recurring items on their dates and stops at their end date', () => {
    // Given €1000 today and rent of €100 on the 1st through Dec only
    const { points, endValue } = balanceForecast({
      accounts: [account(1, 1000)],
      transactions: [],
      transfers: noTransfers,
      recurring: [recurring({ end_date: '2026-12-31' })],
      today: '2026-10-31',
    });
    // Then a week in, Nov rent is out; by the end only Nov + Dec were paid
    expect(points.find((p) => p.date === '2026-11-07')?.value).toBe(900);
    expect(endValue).toBe(800);
  });

  it('adds the daily trend and future-dated entries', () => {
    // Given €0 initial, a −€900 row on the first day of the 90-day window, and a future-dated €50 expense
    const transactions = [
      tx('2026-08-03', 900),
      tx('2026-11-15', 50),
    ];
    const { points, trendPerDay } = balanceForecast({
      accounts: [account(1, 0)],
      transactions,
      transfers: noTransfers,
      recurring: [],
      today: '2026-10-31',
    });
    // Then the trend is −€10/day and the future-dated row lands on its date
    expect(trendPerDay).toBeCloseTo(-10);
    expect(points.find((p) => p.date === '2026-11-14')?.value).toBeCloseTo(-900 - 140);
    expect(points.find((p) => p.date === '2026-11-21')?.value).toBeCloseTo(-900 - 50 - 210);
  });

  it('ignores a recurring item that is paused', () => {
    // Given an inactive recurring expense
    const { endValue } = balanceForecast({
      accounts: [account(1, 500)],
      transactions: [],
      transfers: noTransfers,
      recurring: [recurring({ is_active: 0 })],
      today: '2026-10-31',
    });
    expect(endValue).toBe(500);
  });
});

describe('monthlyCashflow', () => {
  it('buckets income and expense by month, zero-filling quiet months', () => {
    // Given income in Aug and expenses in Oct, plus a row on an out-of-scope account
    const rows = monthlyCashflow(
      [tx('2026-08-03', 2000, 'income'), tx('2026-10-10', 40), tx('2026-10-20', 60), tx('2026-10-05', 999, 'expense', 2)],
      new Set([1]),
      '2026-10',
      3,
    );
    // Then there are three months, oldest first, with September empty
    expect(rows).toEqual([
      { month: '2026-08', income: 2000, expense: 0, transferIn: 0, transferOut: 0 },
      { month: '2026-09', income: 0, expense: 0, transferIn: 0, transferOut: 0 },
      { month: '2026-10', income: 0, expense: 100, transferIn: 0, transferOut: 0 },
    ]);
  });
});

describe('monthlyCashflow — transfers for one account', () => {
  const transfer = (from: number | null, to: number | null, amount: number, date: string, to_amount: number | null = null) =>
    ({ from_account_id: from, to_account_id: to, amount, to_amount, date } as TransferWithDetails);

  it('adds transfers in and out of the viewed account by month', () => {
    // Given a transfer out of account 1, one into it (cross-currency), and one between others
    const transfers = [
      transfer(1, 2, 200, '2026-09-10'),
      transfer(3, 1, 100, '2026-10-02', 92.5),
      transfer(2, 3, 999, '2026-10-05'),
    ];
    // When viewing account 1
    const rows = monthlyCashflow([], new Set([1]), '2026-10', 2, { transfers, accountId: 1 });
    // Then out is the sent amount, in is the received amount, and the unrelated one is ignored
    expect(rows).toEqual([
      { month: '2026-09', income: 0, expense: 0, transferIn: 0, transferOut: 200 },
      { month: '2026-10', income: 0, expense: 0, transferIn: 92.5, transferOut: 0 },
    ]);
  });
});

describe('cashflowSummary', () => {
  const month = (m: string, income: number, expense: number, transferIn = 0, transferOut = 0) => ({
    month: m, income, expense, transferIn, transferOut,
  });

  it('averages from the first active month up to the current month', () => {
    // Given an empty first month, two active months and an empty future month
    const rows = [
      month('2026-08', 0, 0),
      month('2026-09', 1000, 600),
      month('2026-10', 1000, 800),
      month('2026-11', 0, 0),
    ];
    // When the current month is October
    const summary = cashflowSummary(rows, '2026-10');
    // Then only Sep and Oct count
    expect(summary?.avgNet).toBe(300);
    expect(summary?.savingsRate).toBeCloseTo(30);
  });

  it('has no savings rate without income and nothing at all without activity', () => {
    expect(cashflowSummary([month('2026-10', 0, 50)], '2026-10'))
      .toEqual({ avgNet: -50, savingsRate: null });
    expect(cashflowSummary([month('2026-10', 0, 0)], '2026-10')).toBeNull();
  });

  it('counts transfers as activity but not toward the net or the rate', () => {
    // Given an account fed only by a transfer in September, then income and expense in October
    const rows = [month('2026-08', 0, 0), month('2026-09', 0, 0, 500), month('2026-10', 1000, 400, 0, 300)];
    // Then September starts the average, and the transfers move neither figure
    expect(cashflowSummary(rows, '2026-10')).toEqual({ avgNet: 300, savingsRate: 60 });
  });
});

describe('niceAxis', () => {
  it('rounds a narrow high range to round steps instead of starting at the lowest point', () => {
    // Given a balance moving between 4,820 and 5,130
    const axis = niceAxis(4820, 5130);
    // Then the axis runs 4,800–5,200 in steps of 100
    expect(axis).toEqual({ min: 4800, max: 5200, step: 100, sections: 4 });
  });

  it('includes a zero line when the range crosses zero', () => {
    // Given a balance projected to go from 900 to −350
    const axis = niceAxis(-350, 900);
    // Then 0 is one of the gridlines
    expect(axis.min).toBe(-500);
    expect(axis.max).toBe(1000);
    expect(Number.isInteger(-axis.min / axis.step)).toBe(true);
  });

  it('still has a height when every value is the same', () => {
    // Given a flat balance of 1,000
    const axis = niceAxis(1000, 1000);
    // Then the axis spans at least one step
    expect(axis.max).toBeGreaterThan(axis.min);
    expect(axis.min).toBeLessThanOrEqual(1000);
    expect(axis.max).toBeGreaterThanOrEqual(1000);
  });

  it('handles an all-zero series', () => {
    expect(niceAxis(0, 0)).toEqual({ min: 0, max: 1, step: 1, sections: 1 });
  });
});

